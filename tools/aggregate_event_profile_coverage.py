#!/usr/bin/env python3
"""Combine yearly all-event profile-coverage audits into one retained report.

Input layout:
  <input-dir>/<season>/summary.json
Each summary is generated by audit_event_population.py --all-events.
The report contains aggregate counts and event-level metadata only; it never copies
source CSV rows, player names, or player IDs.
"""
import argparse
import csv
import json
from datetime import datetime, timezone
from pathlib import Path

COUNT_FIELDS = (
    "event_count",
    "raw_event_rows",
    "eligible_matches",
    "eligible_server_sides",
    "rateable_server_sides",
    "unrateable_server_sides",
    "events_with_unrateable_sides",
    "tour_prior_sides",
    "events_with_tour_prior_sides",
)
FALLBACK_FIELDS = (
    "profile_exists_without_rate_occurrences",
    "no_player_profile_in_history_occurrences",
    "server_role_fallback_occurrences",
    "returner_role_fallback_occurrences",
    "distinct_fallback_player_ids",
    "distinct_fallback_player_role_keys",
)


def _integer(value):
    return int(value or 0)


def load_year_summaries(input_dir, start_year, end_year):
    root = Path(input_dir)
    summaries = []
    missing = []
    for year in range(start_year, end_year + 1):
        path = root / str(year) / "summary.json"
        if not path.is_file():
            missing.append(year)
            continue
        with path.open(encoding="utf-8") as source:
            summary = json.load(source)
        if _integer(summary.get("season")) != year:
            raise ValueError(
                f"{path} reports season {summary.get('season')!r}, expected {year}"
            )
        if not isinstance(summary.get("events"), list):
            raise ValueError(f"{path} has no event list")
        if _integer(summary.get("event_count")) != len(summary["events"]):
            raise ValueError(
                f"{path} event_count does not match its event records"
            )
        summaries.append(summary)

    if missing:
        raise FileNotFoundError(
            "Missing yearly summaries for: " + ", ".join(map(str, missing))
        )
    if len(summaries) != end_year - start_year + 1:
        raise ValueError("The audit range is incomplete")
    return summaries


def aggregate_summaries(summaries, start_year, end_year):
    season_rows = []
    event_rows = []
    totals = {field: 0 for field in COUNT_FIELDS}
    fallback_totals = {field: 0 for field in FALLBACK_FIELDS}
    sources = []

    for summary in summaries:
        season = _integer(summary["season"])
        fallback = summary.get("fallback_diagnostics") or {}
        row = {
            "season": season,
            "source": summary.get("source", "unknown"),
            **{field: _integer(summary.get(field)) for field in COUNT_FIELDS},
            **{field: _integer(fallback.get(field)) for field in FALLBACK_FIELDS},
        }
        row["rateable_pct"] = (
            100.0 * row["rateable_server_sides"] / row["eligible_server_sides"]
            if row["eligible_server_sides"] else 0.0
        )
        row["tour_prior_pct"] = (
            100.0 * row["tour_prior_sides"] / row["eligible_server_sides"]
            if row["eligible_server_sides"] else 0.0
        )
        season_rows.append(row)

        for field in COUNT_FIELDS:
            totals[field] += row[field]
        for field in FALLBACK_FIELDS:
            fallback_totals[field] += row[field]

        metadata = summary.get("source_metadata") or {}
        sources.append({
            "season": season,
            "source": row["source"],
            "url": metadata.get("url"),
            "fetchedAtUtc": metadata.get("fetchedAtUtc"),
            "latestMatchDate": metadata.get("latestMatchDate"),
            "matchRows": metadata.get("matchRows"),
            "sha256": metadata.get("sha256"),
        })

        for event in summary["events"]:
            event_row = dict(event)
            event_row["season"] = season
            event_row["source"] = row["source"]
            event_rows.append(event_row)

    totals["rateable_pct"] = (
        100.0 * totals["rateable_server_sides"] / totals["eligible_server_sides"]
        if totals["eligible_server_sides"] else 0.0
    )
    totals["tour_prior_pct"] = (
        100.0 * totals["tour_prior_sides"] / totals["eligible_server_sides"]
        if totals["eligible_server_sides"] else 0.0
    )

    return {
        "schema_version": 1,
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "start_year": start_year,
        "end_year": end_year,
        "season_count": len(season_rows),
        "scope": "all mapped ATP tour events in each season's selected source",
        "totals": totals,
        "fallback_diagnostics": fallback_totals,
        "seasons": season_rows,
        "events": event_rows,
        "source_manifests": sources,
        "raw_source_csv_included": False,
        "player_names_and_ids_published": False,
        "interpretation": {
            "rateability": "A side is rateable when the calculation has finite player-role inputs, including an explicitly counted neutral tour-average prior where personal evidence is unavailable.",
            "tour_prior": "A side counted here used a neutral tour-average prior for at least one of its two player-role inputs; this is not player-specific historical evidence.",
            "source_scope": "Coverage describes the selected source and mapped event names only; it does not establish Tennis Abstract's match population.",
        },
    }


def _write_csv(path, rows):
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    keys = []
    seen = set()
    for row in rows:
        for key in row:
            if key not in seen:
                seen.add(key)
                keys.append(key)
    with path.open("w", newline="", encoding="utf-8") as target:
        writer = csv.DictWriter(target, fieldnames=keys, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def render_markdown(report):
    totals = report["totals"]
    fallback = report["fallback_diagnostics"]
    lines = [
        f"# ATP player-profile coverage audit: {report['start_year']}–{report['end_year']}",
        "",
        f"Generated: {report['generated_utc']}",
        "",
        "## Scope and aggregate result",
        "",
        f"- Seasons audited: **{report['season_count']}**",
        f"- Mapped event-seasons: **{totals['event_count']:,}**",
        f"- Eligible matches: **{totals['eligible_matches']:,}**",
        f"- Eligible server sides: **{totals['eligible_server_sides']:,}**",
        f"- Rateable sides: **{totals['rateable_server_sides']:,} ({totals['rateable_pct']:.3f}%)**",
        f"- Unrateable sides: **{totals['unrateable_server_sides']:,}**",
        f"- Sides using at least one neutral tour-average prior: **{totals['tour_prior_sides']:,} ({totals['tour_prior_pct']:.3f}%)**",
        "",
        "Rateability is not the same as player-specific evidence. A neutral tour-average prior completes the expected-aces input but does not recover an individual player's serve or return tendency.",
        "",
        "## Fallback diagnostics",
        "",
        "| Diagnostic | Count |",
        "|---|---:|",
        f"| Missing role estimate although a player profile record exists | {fallback['profile_exists_without_rate_occurrences']:,} |",
        f"| No player profile found in the history window | {fallback['no_player_profile_in_history_occurrences']:,} |",
        f"| Server-role fallback occurrences | {fallback['server_role_fallback_occurrences']:,} |",
        f"| Returner-role fallback occurrences | {fallback['returner_role_fallback_occurrences']:,} |",
        f"| Distinct fallback player IDs (per season, summed) | {fallback['distinct_fallback_player_ids']:,} |",
        "",
        "These fallback counts are role occurrences, not necessarily unique people across seasons. The report deliberately omits player names and IDs.",
        "",
        "## Season-by-season coverage",
        "",
        "| Season | Source | Event-seasons | Matches | Sides | Rateable | Tour-prior sides | Prior share |",
        "|---:|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in report["seasons"]:
        lines.append(
            f"| {row['season']} | {row['source']} | {row['event_count']:,} | "
            f"{row['eligible_matches']:,} | {row['eligible_server_sides']:,} | "
            f"{row['rateable_pct']:.2f}% | {row['tour_prior_sides']:,} | "
            f"{row['tour_prior_pct']:.2f}% |"
        )
    lines.extend([
        "",
        "## Event-level files",
        "",
        "- coverage-by-event.csv: mapped event-season rows and aggregate fallback counts.",
        "- coverage-by-season.csv: one row per audited season.",
        "- summary.json: machine-readable totals, source manifests and scope notes.",
        "",
        "## Limitations",
        "",
        "- Only mapped event names in the selected source are counted; this is not a claim that every ATP event or every match in each season is present.",
        "- A successful audit establishes reproducible coverage against the selected archive, not the correctness of Tennis Abstract's population or the physical truth of the Surface Speed metric.",
        "- A side can be rateable through a neutral prior while still having incomplete player-specific evidence.",
        "- Source CSV files, player names and player IDs are not included in this report.",
        "",
    ])
    return "\n".join(lines)


def write_report(report, output_dir):
    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    (output / "summary.json").write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    _write_csv(output / "coverage-by-season.csv", report["seasons"])
    _write_csv(output / "coverage-by-event.csv", report["events"])
    (output / "README.md").write_text(render_markdown(report), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(
        description="Aggregate per-season ATP event profile coverage audit outputs."
    )
    parser.add_argument("--input-dir", required=True)
    parser.add_argument("--start-year", type=int, default=1991)
    parser.add_argument("--end-year", type=int, required=True)
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args()
    if args.start_year > args.end_year:
        parser.error("--start-year must not be after --end-year")
    summaries = load_year_summaries(args.input_dir, args.start_year, args.end_year)
    report = aggregate_summaries(summaries, args.start_year, args.end_year)
    write_report(report, args.output_dir)
    print(json.dumps({
        "start_year": report["start_year"],
        "end_year": report["end_year"],
        "season_count": report["season_count"],
        "event_seasons": report["totals"]["event_count"],
        "eligible_matches": report["totals"]["eligible_matches"],
        "eligible_server_sides": report["totals"]["eligible_server_sides"],
        "rateable_server_sides": report["totals"]["rateable_server_sides"],
        "tour_prior_sides": report["totals"]["tour_prior_sides"],
        "output_dir": str(Path(args.output_dir)),
    }, indent=2))


if __name__ == "__main__":
    main()
